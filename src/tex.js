// Export to a single, standalone .tex file in the same structure as the original resume engine.
// Compiles on Overleaf or with pdflatex as-is.

const esc = (s = '') =>
  String(s)
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/([&%$#_{}])/g, '\\$1')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}')
    .replace(/\|/g, '\\textbar{}')
    .replace(/₹/g, 'Rs.\\ ');

const ICON = { email: 'faEnvelope', phone: 'faPhone', linkedin: 'faLinkedin', github: 'faGithub', website: 'faGlobe', location: 'faMapMarker*' };

export function toTex(r) {
  const p = r.personal;
  const L = [];
  L.push(`% Generated by Rizzume — ${new Date().toISOString().slice(0, 10)}
\\documentclass[a4paper,10pt]{article}
\\usepackage[T1]{fontenc}
\\usepackage{lmodern}
\\usepackage[margin=0.5in]{geometry}
\\usepackage{enumitem}
\\usepackage{titlesec}
\\usepackage{hyperref}
\\usepackage{fontawesome5}
\\usepackage{setspace}

\\pagestyle{empty}
\\setstretch{1.06}
\\setlength{\\parindent}{0pt}
\\hypersetup{colorlinks=true, allcolors=black}

\\titleformat{\\section}{\\large\\bfseries}{}{0em}{}[\\titlerule]
\\titlespacing{\\section}{0pt}{9pt}{4pt}

\\newcommand{\\resumeItemListStart}{\\begin{itemize}[leftmargin=1.15em, itemsep=3pt, topsep=3pt, partopsep=0pt, parsep=0pt]}
\\newcommand{\\resumeItemListEnd}{\\end{itemize}\\vspace{5pt}}
\\newcommand{\\resumeEntryTitle}[2]{\\textbf{#1} \\hfill \\textbf{#2} \\\\[-9pt]}

\\begin{document}
`);
  // Header
  const contacts = [];
  if (p.email) contacts.push(`\\${ICON.email} \\ \\href{mailto:${p.email}}{${esc(p.email)}}`);
  if (p.phone) contacts.push(`\\${ICON.phone} \\ ${esc(p.phone)}`);
  if (p.linkedin) contacts.push(`\\${ICON.linkedin} \\ \\href{https://linkedin.com/in/${p.linkedin}}{linkedin.com/in/${esc(p.linkedin)}}`);
  if (p.github) contacts.push(`\\${ICON.github} \\ \\href{https://github.com/${p.github}}{github.com/${esc(p.github)}}`);
  if (p.website) contacts.push(`\\${ICON.website} \\ \\href{${/^https?:/.test(p.website) ? p.website : 'https://' + p.website}}{${esc(p.website)}}`);
  if (p.location) contacts.push(`\\faMapMarker* \\ ${esc(p.location)}`);
  L.push(`\\noindent
\\begin{minipage}[t]{0.60\\textwidth}
  \\raggedright
  {\\fontsize{24}{26}\\selectfont \\bfseries ${esc(p.name)}} \\\\[3pt]
  \\textit{${esc(p.title)}}
\\end{minipage}%
\\begin{minipage}[t]{0.40\\textwidth}
  \\raggedleft
  \\vspace{-17pt}
  \\small
  ${contacts.join(' \\\\[3pt]\n  ')} \\\\[3pt]
\\end{minipage}
\\vspace{2pt}
`);

  for (const s of r.sections) {
    if (!s.visible) continue;
    L.push(`\\section*{${esc(s.title)}}`);
    if (s.kind === 'text') L.push(esc(s.text) + '\n');
    if (s.kind === 'lines') {
      const rows = s.rows.filter((x) => x.label || x.value).map((x) => `\\textbf{${esc(x.label)}:} ${esc(x.value)}`);
      L.push(rows.join(' \\\\\n') + '\n');
    }
    if (s.kind === 'entries') {
      s.items.forEach((it, i) => {
        const bullets = it.bullets.filter((b) => b.text);
        const list = bullets.length
          ? `\\resumeItemListStart\n${bullets.map((b) => `  \\item ${esc(b.text)}`).join('\n')}\n\\resumeItemListEnd`
          : '';
        let right = esc(it.right);
        if (it.url) right = `\\href{${it.url}}{${/github\.com/.test(it.url) ? '\\faGithub' : '\\faLink'}\\ ${right}}`;
        if (it.bulletsOnly) return L.push(list);
        if (s.layout === 'school') {
          L.push(`${i ? '\\vspace{6pt}\n' : ''}\\textbf{${esc(it.title)}} \\hfill \\textit{${right}} \\\\\n${esc(it.subtitle)} \\hfill \\textbf{${esc(it.subRight)}}\n`);
        } else if (s.layout === 'compact') {
          const next = s.items[i + 1];
          const end = next && !next.bulletsOnly ? ' \\\\[5pt]' : '';
          L.push(`\\textbf{${esc(it.title)}}${it.detail ? ` — ${esc(it.detail)}` : ''} \\hfill ${right}${end}${list ? '\n' + list : ''}`);
        } else {
          const title = esc(it.title) + (it.detail ? ` — ${esc(it.detail)}` : '');
          L.push(`\\resumeEntryTitle{${title}}{${right}}\n${list}\n`);
        }
      });
    }
    L.push('');
  }
  L.push('\\end{document}\n');
  return L.join('\n');
}
